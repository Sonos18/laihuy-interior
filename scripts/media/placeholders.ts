// Generates tiny blurred placeholders for hero photographs (app/media/placeholders.generated.ts).
//
// A hero photograph takes 0.2–2.4s to arrive (cold CDN cache, a 2560px master on a 3x phone).
// Until it does, the hero showed a flat Obsidian box. Each placeholder is the same photograph at
// 32px wide (~200 bytes as WebP), inlined in the page, drawn blurred behind the <img> so the
// hero carries the room's own colours from the first paint.
//
// Sources, in order: the local master under public/images (when present), otherwise the public
// w400 variant in Supabase Storage. Remote needs NUXT_PUBLIC_SUPABASE_URL in the process
// environment; the script never reads .env.
//
// Usage: pnpm media:placeholders   (re-run when a hero photograph or a project cover changes)
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import process from 'node:process'
import sharp from 'sharp'
import { publicObjectUrl, REPO_ROOT } from './lib'

const OUTPUT = join(REPO_ROOT, 'app/media/placeholders.generated.ts')
const CATALOG = join(REPO_ROOT, 'app/media/catalog.generated.ts')
const PLACEHOLDER_WIDTH = 32

// Hero photographs that are not a project cover (see the `heroImage` of each page).
const EXTRA_HERO_PATHS = [
  'company/workshop/3.webp',
  'company/workshop/4.webp',
  'company/workshop/5.webp',
  'projects/codi-boutique-hotel/sanh-don/2.webp',
  'projects/nha-vuon-chily/5.webp'
]

const projectCoverPaths = (): string[] => {
  const source = readFileSync(CATALOG, 'utf8')
  return [...source.matchAll(/cover: \{ path: '([^']+)'/g)].map(match => match[1] as string)
}

const variantPath = (path: string, width: number): string => path.replace(/\.webp$/, `-w${width}.webp`)

const loadSource = async (path: string): Promise<Buffer> => {
  const local = join(REPO_ROOT, 'public/images', path)
  if (existsSync(local)) {
    return readFileSync(local)
  }

  const supabaseUrl = process.env.NUXT_PUBLIC_SUPABASE_URL
  if (!supabaseUrl) {
    throw new Error(`[media] ${path} is not in public/images and NUXT_PUBLIC_SUPABASE_URL is not set`)
  }

  const response = await fetch(publicObjectUrl(supabaseUrl, variantPath(path, 400)))
  if (!response.ok) {
    throw new Error(`[media] ${path}: HTTP ${response.status}`)
  }
  return Buffer.from(await response.arrayBuffer())
}

const run = async () => {
  const paths = [...new Set([...projectCoverPaths(), ...EXTRA_HERO_PATHS])].sort()
  const entries: string[] = []

  for (const path of paths) {
    const tiny = await sharp(await loadSource(path))
      .resize({ width: PLACEHOLDER_WIDTH })
      .webp({ quality: 50 })
      .toBuffer()
    entries.push(`  '${path}': 'data:image/webp;base64,${tiny.toString('base64')}'`)
  }

  const file = `/**
 * -----------------------------------------------------------------------------
 * AUTO-GENERATED FILE — DO NOT EDIT MANUALLY.
 *
 * Generated by:
 *   pnpm media:placeholders
 *
 * ${PLACEHOLDER_WIDTH}px blurred stand-ins for hero photographs, keyed by storage path.
 * -----------------------------------------------------------------------------
 */
export const heroPlaceholders: Readonly<Record<string, string>> = {
${entries.join(',\n')}
}
`
  writeFileSync(OUTPUT, file, 'utf8')
  console.log(`[media] ${entries.length} placeholders → app/media/placeholders.generated.ts`)
}

await run()
